/**
 * Filter songs by era.
 */
export function filterByEra(library: Song[], eraFilter: EraFilter): Song[] {
  if (eraFilter === '2020s') return library.filter((s) => s.year !== undefined && s.year >= 2020);
  if (eraFilter === '2010s') return library.filter((s) => s.year !== undefined && s.year >= 2010 && s.year <= 2019);
  if (eraFilter === '2000s') return library.filter((s) => s.year !== undefined && s.year < 2010);
  return library;
}

/**
 * Filter songs by challenge gauntlet theme.
 */
export function filterByChallengeTheme(library: Song[], theme?: ChallengeTheme): Song[] {
  if (!theme || theme === 'standard') return library;

  let filtered: Song[];
  switch (theme) {
    case 'era-90s':
      filtered = library.filter((s) => s.year !== undefined && s.year >= 1990 && s.year <= 1999);
      break;
    case 'era-2000s':
      filtered = library.filter((s) => s.year !== undefined && s.year >= 2000 && s.year <= 2009);
      break;
    case 'era-2010s':
      filtered = library.filter((s) => s.year !== undefined && s.year >= 2010 && s.year <= 2019);
      break;
    case 'era-2020s':
      filtered = library.filter((s) => s.year !== undefined && s.year >= 2020);
      break;
    case 'year-2016':
      filtered = library.filter((s) => s.year === 2016);
      break;
    case 'genre-hiphop':
      filtered = library.filter((s) => {
        const g = s.genre.toLowerCase();
        return g.includes('hip-hop') || g.includes('rap') || g.includes('trap') || g.includes('drill') || g.includes('boom');
      });
      break;
    case 'genre-rnb':
      filtered = library.filter((s) => {
        const g = s.genre.toLowerCase();
        return g.includes('r&b') || g.includes('soul') || g.includes('neo-soul');
      });
      break;
    default:
      filtered = library;
  }

  // Gracefully fallback to full library if filter produces too few candidates
  return filtered.length >= 8 ? filtered : library;
}


/**
 * Finds the optimal solo-monopoly-safe song for a slot.
 */
export function findOptimalPickForSlot(
  slotId: string,
  idealEnergy: number,
  draftedSoloArtists: string[],
  eraFilter: EraFilter = 'all'
): Song | null {
  const eraPool = filterByEra(SONG_LIBRARY, eraFilter);
  const draftedSet = new Set(draftedSoloArtists.map((a) => a.trim()));

  let candidates = eraPool.filter((s) => s.slots.includes(slotId as SlotId));
  if (candidates.length === 0) candidates = eraPool;

  const safe = candidates.filter((s) => !draftedSet.has(s.artist.trim()));
  const pool = safe.length > 0 ? safe : candidates;

  let best: Song | null = null;
  let bestDelta = Infinity;
  for (const song of pool) {
    const delta = Math.abs(song.energy - idealEnergy);
    if (delta < bestDelta) {
      bestDelta = delta;
      best = song;
    }
  }
  return best;
}

/**
 * Main options getter using Candidate Generator Engine.
 */
export function getOptionsForSlot(
  slotId: string,
  count: number = 5,
  eraFilter: EraFilter = 'all',
  seed?: string | null,
  context?: Partial<CandidateContext>
): Song[] {
  const fullContext: CandidateContext = {
    slotId: slotId as SlotId,
    era: eraFilter,
    seed: seed ?? null,
    rerollIndex: context?.rerollIndex ?? 0,
    draftedSongIds: context?.draftedSongIds ?? [],
    draftedArtists: context?.draftedArtists ?? [],
    recentlyShownSongIds: context?.recentlyShownSongIds ?? [],
    recentlyShownArtists: context?.recentlyShownArtists ?? [],
    theme: context?.theme,
    budgetRemaining: context?.budgetRemaining,
  };
  return generateCandidatePool(fullContext, count);
}
