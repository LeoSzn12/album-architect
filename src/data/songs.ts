/**
 * Returns the era-filtered subset of the SONG_LIBRARY.
 *
 * Era buckets:
 *   '2020s'  — 2020 and later
 *   '2010s'  — 2010–2019 (Golden Era)
 *   '2000s'  — before 2010, including pre-2000 classics (Illmatic, Ruff Ryders, etc.)
 *   'all'    — entire library (no filter)
 *
 * Falling back from a specific era to 'all' must be explicit in the call site;
 * this function never silently widens the pool.
 */
export function filterByEra(library: Song[], eraFilter: EraFilter): Song[] {
  if (eraFilter === '2020s') return library.filter((s) => s.year !== undefined && s.year >= 2020);
  if (eraFilter === '2010s') return library.filter((s) => s.year !== undefined && s.year >= 2010 && s.year <= 2019);
  if (eraFilter === '2000s') return library.filter((s) => s.year !== undefined && s.year < 2010);
  return library;
}

/**
 * Finds the optimal solo-monopoly-safe song for a slot:
 * - Eligible for the slot (or any song if none are tagged)
 * - Within the requested era
 * - Solo primary artist not already drafted (so no monopoly penalty)
 * - Minimum absolute delta from the slot's ideal energy
 *
 * Used by the A&R Hindsight analysis to compute the "theoretical optimal" picks.
 */
export function findOptimalPickForSlot(
  slotId: string,
  idealEnergy: number,
  draftedSoloArtists: string[],
  eraFilter: EraFilter = 'all'
): Song | null {
  const eraPool = filterByEra(SONG_LIBRARY, eraFilter);
  const draftedSet = new Set(draftedSoloArtists.map((a) => a.trim()));

  // Prefer songs explicitly tagged for this slot.
  let candidates = eraPool.filter((s) => s.slots.includes(slotId as SlotId));
  if (candidates.length === 0) candidates = eraPool;

  // Exclude tracks whose solo primary artist is already drafted at cap 1.
  const safe = candidates.filter((s) => !draftedSet.has(s.artist.trim()));

  // If everything would trip a monopoly, fall back to the full candidate list
  // (we still want to surface an "optimal" pick even if it costs a penalty).
  const pool = safe.length > 0 ? safe : candidates;

  let best: Song | null = null;
  let bestDelta = Infinity;
  for (const song of pool) {
    const delta = Math.abs(song.energy - idealEnergy);
    if (delta < bestDelta) {
      bestDelta = delta;
      best = song;
    }
  }
  return best;
}

/**
 * Utility function to filter options for a specific draft slot and Era filter.
 * If a seed string is provided, shuffling is 100% deterministic (perfect for Head-to-Head 1v1 challenges!).
 */
export function getOptionsForSlot(
  slotId: string,
  count: number = 4,
  eraFilter: EraFilter = 'all',
  seed?: string | null
): Song[] {
  // 1. Filter entire library by Era first
  const eraPool = filterByEra(SONG_LIBRARY, eraFilter);

  // Helper shuffle function using seed PRNG or random
  const shuffle = <T>(arr: T[], seedTag: string): T[] => {
    if (seed) {
      return seededShuffle(arr, `${seed}-${slotId}-${seedTag}`);
    }
    return [...arr].sort(() => 0.5 - Math.random());
  };

  // 2. Find matching songs for this slot within the Era Pool
  const matching = eraPool.filter((song) => song.slots.includes(slotId as SlotId));

  if (matching.length >= count) {
    // Shuffle and pick `count` options from matching era songs
    return shuffle(matching, 'match').slice(0, count);
  }

  // 3. If not enough direct slot matches in this era, fill with other songs from the SAME ERA
  const remainingInEra = eraPool.filter((song) => !matching.includes(song));
  const fallbackInEra = shuffle(remainingInEra, 'fallbackEra').slice(0, count - matching.length);

  const eraCombined = [...matching, ...fallbackInEra];
  if (eraCombined.length >= count) {
    return eraCombined.slice(0, count);
  }

  // Fallback to broader matching if era pool is small
  const globalRemaining = SONG_LIBRARY.filter((s) => !eraCombined.includes(s));
  return [...eraCombined, ...shuffle(globalRemaining, 'fallbackGlobal').slice(0, count - eraCombined.length)];
}

